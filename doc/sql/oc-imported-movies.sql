-- open-credits: the movies loaded by the importer, newest first, with their latest reading.
-- Read-only; run with: ssh vps-agent run open-credits/doc/sql/oc-imported-movies.sql
SELECT W.ID_MOVIE, W.ORIGINAL_TITLE, W.YEAR, COUNT(DISTINCT S.ID_OC_SUBMISSION) AS READINGS,
       MAX(S.SUBMITTED_AT) AS LAST_UTC,
       (SELECT COUNT(*) FROM T_WC_OC_TEXT_LINE L JOIN T_WC_OC_SEGMENT G ON G.ID_OC_SEGMENT = L.ID_OC_SEGMENT
        WHERE G.ID_OC_SUBMISSION = (SELECT S2.ID_OC_SUBMISSION FROM T_WC_OC_SUBMISSION S2 JOIN T_WC_OC_COPY C2 ON C2.ID_OC_COPY = S2.ID_OC_COPY
                                    WHERE C2.ID_OC_WORK = W.ID_OC_WORK ORDER BY S2.SUBMITTED_AT DESC LIMIT 1)) AS LINES_LAST
FROM T_WC_OC_WORK W
JOIN T_WC_OC_COPY C ON C.ID_OC_WORK = W.ID_OC_WORK
JOIN T_WC_OC_SUBMISSION S ON S.ID_OC_COPY = C.ID_OC_COPY AND S.DELETED = 0
GROUP BY W.ID_OC_WORK
ORDER BY LAST_UTC DESC;
