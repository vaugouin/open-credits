-- open-credits pilot (OPEN-CREDITS-003): candidate titles in Philippe's Plex library.
-- Read-only. Movies are T_WC_TMDB_PLEX_MOVIE rows with DATA_TYPE = 1 (Plex metadata_type);
-- a Plex media is one copy, a media part one file.

-- 1. The titles already named for the pilot, and the extra ones suggested on 2026-10-17
SELECT m.ID_MOVIE, m.ORIGINAL_TITLE, m.TITLE, m.RELEASE_YEAR, m.ORIGINAL_LANGUAGE,
       COUNT(DISTINCT pm.ID_PLEX_MEDIA) AS copies,
       GROUP_CONCAT(DISTINCT pm.QUALITY_TEXT ORDER BY pm.QUALITY_TEXT SEPARATOR ', ') AS qualities
FROM T_WC_TMDB_MOVIE m
LEFT JOIN T_WC_TMDB_PLEX_MOVIE p ON p.ID_MOVIE = m.ID_MOVIE AND p.DATA_TYPE = 1 AND COALESCE(p.DELETED, 0) = 0
LEFT JOIN T_WC_TMDB_PLEX_MEDIA pm ON pm.ID_PLEX_MOVIE = p.ID_PLEX_MOVIE AND COALESCE(pm.DELETED, 0) = 0
WHERE m.ID_MOVIE IN (299534, 76600, 426, 251516, 129, 843, 535167, 496243, 60243, 11, 863, 9487, 78)
   OR (m.TITLE IN ('Code 8', 'Ballad of a Small Player') AND m.RELEASE_YEAR >= 2019)
GROUP BY m.ID_MOVIE, m.ORIGINAL_TITLE, m.TITLE, m.RELEASE_YEAR, m.ORIGINAL_LANGUAGE
ORDER BY copies DESC, m.TITLE;

-- 2. Movies in Plex per original language, for the non-Latin scripts
SELECT m.ORIGINAL_LANGUAGE, COUNT(DISTINCT m.ID_MOVIE) AS movies_in_plex
FROM T_WC_TMDB_PLEX_MOVIE p
JOIN T_WC_TMDB_MOVIE m ON m.ID_MOVIE = p.ID_MOVIE
WHERE p.DATA_TYPE = 1 AND COALESCE(p.DELETED, 0) = 0
  AND m.ORIGINAL_LANGUAGE IN ('ja', 'zh', 'cn', 'ko', 'fa', 'ar', 'he', 'ru', 'hi', 'ta', 'te', 'th', 'el', 'uk', 'bn')
GROUP BY m.ORIGINAL_LANGUAGE
ORDER BY movies_in_plex DESC;

-- 3. The ten most popular movies in Plex per non-Latin original language, with their best copy
SELECT * FROM (
  SELECT m.ORIGINAL_LANGUAGE, m.ID_MOVIE, m.ORIGINAL_TITLE, m.TITLE, m.RELEASE_YEAR,
         ROUND(m.POPULARITY, 1) AS popularity, m.VOTE_COUNT,
         MAX(pm.MEDIA_HEIGHT) AS best_height, COUNT(DISTINCT pm.ID_PLEX_MEDIA) AS copies,
         ROW_NUMBER() OVER (PARTITION BY m.ORIGINAL_LANGUAGE ORDER BY m.VOTE_COUNT DESC) AS rank_in_language
  FROM T_WC_TMDB_PLEX_MOVIE p
  JOIN T_WC_TMDB_MOVIE m ON m.ID_MOVIE = p.ID_MOVIE
  JOIN T_WC_TMDB_PLEX_MEDIA pm ON pm.ID_PLEX_MOVIE = p.ID_PLEX_MOVIE AND COALESCE(pm.DELETED, 0) = 0
  WHERE p.DATA_TYPE = 1 AND COALESCE(p.DELETED, 0) = 0
    AND m.ORIGINAL_LANGUAGE IN ('ja', 'zh', 'cn', 'ko', 'fa', 'ar', 'he', 'ru', 'hi', 'ta', 'th')
  GROUP BY m.ORIGINAL_LANGUAGE, m.ID_MOVIE, m.ORIGINAL_TITLE, m.TITLE, m.RELEASE_YEAR, m.POPULARITY, m.VOTE_COUNT
) ranked
WHERE rank_in_language <= 10
ORDER BY ORIGINAL_LANGUAGE, rank_in_language;

-- 4. Movies with two copies or more of clearly different quality (for the two-copy case)
SELECT m.ID_MOVIE, m.TITLE, m.RELEASE_YEAR, m.ORIGINAL_LANGUAGE, m.VOTE_COUNT,
       COUNT(DISTINCT pm.ID_PLEX_MEDIA) AS copies,
       GROUP_CONCAT(CONCAT(pm.MEDIA_HEIGHT, 'p ', ROUND(pm.MEDIA_FPS, 3), 'fps ', ROUND(pm.MEDIA_DURATION / 60000, 1), 'min')
                    ORDER BY pm.MEDIA_HEIGHT DESC SEPARATOR ' | ') AS copies_detail
FROM T_WC_TMDB_PLEX_MOVIE p
JOIN T_WC_TMDB_MOVIE m ON m.ID_MOVIE = p.ID_MOVIE
JOIN T_WC_TMDB_PLEX_MEDIA pm ON pm.ID_PLEX_MOVIE = p.ID_PLEX_MOVIE AND COALESCE(pm.DELETED, 0) = 0
WHERE p.DATA_TYPE = 1 AND COALESCE(p.DELETED, 0) = 0
GROUP BY m.ID_MOVIE, m.TITLE, m.RELEASE_YEAR, m.ORIGINAL_LANGUAGE, m.VOTE_COUNT
HAVING copies >= 2 AND MAX(pm.MEDIA_HEIGHT) >= 1080 AND MIN(pm.MEDIA_HEIGHT) <= 576
ORDER BY m.VOTE_COUNT DESC
LIMIT 25;

-- 5. Movies whose copy is split into several files (cd1 / cd2)
SELECT m.ID_MOVIE, m.TITLE, m.RELEASE_YEAR, m.ORIGINAL_LANGUAGE, m.VOTE_COUNT,
       pm.MEDIA_HEIGHT, COUNT(pp.ID_PLEX_MEDIA_PART) AS parts
FROM T_WC_TMDB_PLEX_MOVIE p
JOIN T_WC_TMDB_MOVIE m ON m.ID_MOVIE = p.ID_MOVIE
JOIN T_WC_TMDB_PLEX_MEDIA pm ON pm.ID_PLEX_MOVIE = p.ID_PLEX_MOVIE AND COALESCE(pm.DELETED, 0) = 0
JOIN T_WC_TMDB_PLEX_MEDIA_PART pp ON pp.ID_PLEX_MEDIA = pm.ID_PLEX_MEDIA AND COALESCE(pp.DELETED, 0) = 0
WHERE p.DATA_TYPE = 1 AND COALESCE(p.DELETED, 0) = 0
GROUP BY m.ID_MOVIE, m.TITLE, m.RELEASE_YEAR, m.ORIGINAL_LANGUAGE, m.VOTE_COUNT, pm.ID_PLEX_MEDIA, pm.MEDIA_HEIGHT
HAVING parts >= 2
ORDER BY m.VOTE_COUNT DESC
LIMIT 25;

-- 6. Movies with copies tagged as different editions (director's cut, extended...)
SELECT m.ID_MOVIE, m.TITLE, m.RELEASE_YEAR, m.VOTE_COUNT,
       COUNT(DISTINCT pm.ID_PLEX_MEDIA) AS copies,
       GROUP_CONCAT(DISTINCT COALESCE(NULLIF(pp.FILE_EDITION, ''), '(none)') ORDER BY pp.FILE_EDITION SEPARATOR ' | ') AS editions,
       GROUP_CONCAT(DISTINCT ROUND(pm.MEDIA_DURATION / 60000) ORDER BY pm.MEDIA_DURATION SEPARATOR ', ') AS minutes
FROM T_WC_TMDB_PLEX_MOVIE p
JOIN T_WC_TMDB_MOVIE m ON m.ID_MOVIE = p.ID_MOVIE
JOIN T_WC_TMDB_PLEX_MEDIA pm ON pm.ID_PLEX_MOVIE = p.ID_PLEX_MOVIE AND COALESCE(pm.DELETED, 0) = 0
JOIN T_WC_TMDB_PLEX_MEDIA_PART pp ON pp.ID_PLEX_MEDIA = pm.ID_PLEX_MEDIA AND COALESCE(pp.DELETED, 0) = 0
WHERE p.DATA_TYPE = 1 AND COALESCE(p.DELETED, 0) = 0
GROUP BY m.ID_MOVIE, m.TITLE, m.RELEASE_YEAR, m.VOTE_COUNT
HAVING copies >= 2
   AND SUM(pp.FILE_EDITION REGEXP 'director|extended|unrated|final cut|theatrical|uncut') > 0
   AND MAX(pm.MEDIA_DURATION) - MIN(pm.MEDIA_DURATION) > 300000
ORDER BY m.VOTE_COUNT DESC
LIMIT 25;

-- 7. French films, most voted, recent and older (for the French profile)
SELECT m.ID_MOVIE, m.ORIGINAL_TITLE, m.RELEASE_YEAR, m.VOTE_COUNT, MAX(pm.MEDIA_HEIGHT) AS best_height
FROM T_WC_TMDB_PLEX_MOVIE p
JOIN T_WC_TMDB_MOVIE m ON m.ID_MOVIE = p.ID_MOVIE
JOIN T_WC_TMDB_PLEX_MEDIA pm ON pm.ID_PLEX_MOVIE = p.ID_PLEX_MOVIE AND COALESCE(pm.DELETED, 0) = 0
WHERE p.DATA_TYPE = 1 AND COALESCE(p.DELETED, 0) = 0 AND m.ORIGINAL_LANGUAGE = 'fr'
GROUP BY m.ID_MOVIE, m.ORIGINAL_TITLE, m.RELEASE_YEAR, m.VOTE_COUNT
ORDER BY m.VOTE_COUNT DESC
LIMIT 15;

-- 8. DVD-quality copies (576p or less, no better copy) of well-known movies
SELECT m.ID_MOVIE, m.TITLE, m.RELEASE_YEAR, m.ORIGINAL_LANGUAGE, m.VOTE_COUNT,
       MAX(pm.MEDIA_HEIGHT) AS best_height, MAX(ROUND(pm.MEDIA_FPS, 3)) AS fps
FROM T_WC_TMDB_PLEX_MOVIE p
JOIN T_WC_TMDB_MOVIE m ON m.ID_MOVIE = p.ID_MOVIE
JOIN T_WC_TMDB_PLEX_MEDIA pm ON pm.ID_PLEX_MOVIE = p.ID_PLEX_MOVIE AND COALESCE(pm.DELETED, 0) = 0
WHERE p.DATA_TYPE = 1 AND COALESCE(p.DELETED, 0) = 0
GROUP BY m.ID_MOVIE, m.TITLE, m.RELEASE_YEAR, m.ORIGINAL_LANGUAGE, m.VOTE_COUNT
HAVING best_height <= 576
ORDER BY m.VOTE_COUNT DESC
LIMIT 15;

-- 9. Series in Plex with the most episodes present (for the TV episode profile)
SELECT s.ID_SERIE, s.PLEX_TITLE, COUNT(e.ID_PLEX_MOVIE) AS episodes_in_plex,
       MIN(e.SEASON_NUMBER) AS first_season, MAX(e.SEASON_NUMBER) AS last_season
FROM T_WC_TMDB_PLEX_MOVIE s
JOIN T_WC_TMDB_PLEX_MOVIE e ON e.DATA_TYPE = 4 AND e.ID_SERIE = s.ID_SERIE AND COALESCE(e.DELETED, 0) = 0
WHERE s.DATA_TYPE = 2 AND COALESCE(s.DELETED, 0) = 0 AND s.ID_SERIE IS NOT NULL
GROUP BY s.ID_SERIE, s.PLEX_TITLE
ORDER BY episodes_in_plex DESC
LIMIT 20;
